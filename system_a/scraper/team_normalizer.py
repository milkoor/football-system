    # 反向映射：繁体 -> 简体
    _REVERSE_MAP: Dict[str, str] = {v: k for k, v in TEAM_NAME_MAP.items()}

    @classmethod
    def to_traditional(cls, name: str) -> str:
        """转换为繁体中文

        Args:
            name: 简体或繁体的队名

        Returns:
            繁体中文队名
        """
        if not name:
            return name

        # 先检查是否已经是繁体
        if name in cls._REVERSE_MAP:
            return name

        # 尝试在映射表中查找
        return cls.TEAM_NAME_MAP.get(name, name)

    @classmethod
    def to_simplified(cls, name: str) -> str:
        """转换为简体中文

        Args:
            name: 简体或繁体的队名

        Returns:
            简体中文队名
        """
        if not name:
            return name

        return cls._REVERSE_MAP.get(name, name)

    @classmethod
    def normalize(cls, name: str, to_format: str = "tw") -> str:
        """标准化队名

        Args:
            name: 原始队名
            to_format: 目标格式，"tw"=繁体，"cn"=简体

        Returns:
            标准化后的队名
        """
        if not name:
            return name

        if to_format == "tw":
            return cls.to_traditional(name)
        else:
            return cls.to_simplified(name)